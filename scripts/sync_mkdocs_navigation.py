#!/usr/bin/env python3
"""Generate MkDocs Awesome Pages navigation from the links in each index.md.

Markdown pages are intentionally never renamed: this keeps links and published
URLs stable. The generated .pages files control sidebar ordering instead.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit

MARKER = "# GENERATED BY scripts/sync_mkdocs_navigation.py; DO NOT EDIT MANUALLY."
# Standard inline Markdown links; images are intentionally excluded.
LINK_RE = re.compile(r"(?<!!)(?:\[[^\]]*\])\(\s*(<[^>]+>|[^\s)]+)(?:\s+[^)]*)?\s*\)")


def iter_markdown_destinations(text: str):
    """Yield inline Markdown link destinations in source/document order."""
    for match in LINK_RE.finditer(text):
        destination = match.group(1).strip()
        if destination.startswith("<") and destination.endswith(">"):
            destination = destination[1:-1].strip()
        yield destination


def resolve_local_target(destination: str, index_file: Path, docs_root: Path) -> Path | None:
    """Resolve an internal Markdown target to a file or directory inside docs/."""
    destination = destination.strip()
    if not destination or destination.startswith("#"):
        return None

    parsed = urlsplit(destination)
    if parsed.scheme or parsed.netloc or not parsed.path:
        return None

    decoded_path = unquote(parsed.path)
    if decoded_path.startswith("/"):
        candidate = docs_root / decoded_path.lstrip("/")
    else:
        candidate = index_file.parent / decoded_path
    candidate = candidate.resolve()

    # A link without an extension can refer to a page or a directory.
    if not candidate.exists() and not candidate.suffix:
        markdown_candidate = candidate.with_suffix(".md")
        index_candidate = candidate / "index.md"
        if markdown_candidate.is_file():
            candidate = markdown_candidate.resolve()
        elif index_candidate.is_file():
            candidate = candidate.resolve()

    try:
        candidate.relative_to(docs_root)
    except ValueError:
        # Never let an index from one section order content outside docs/.
        return None

    if candidate.is_dir():
        return candidate if candidate.exists() else None
    if candidate.is_file() and candidate.suffix.lower() == ".md":
        return candidate

    # Surface broken links to Markdown files in the workflow log; do not turn
    # them into invalid .pages entries. The regular MkDocs build remains the
    # authoritative build check.
    if decoded_path.lower().endswith(".md"):
        print(
            f"WARNING: link locale non trovato in {index_file.relative_to(docs_root)}: {destination}",
            file=sys.stderr,
        )
    return None


def nav_item_for_target(target: Path, index_file: Path, docs_root: Path) -> str | None:
    """Return a direct child page/folder name usable in a .pages nav list."""
    if target.resolve() == index_file.resolve():
        return None

    parent = index_file.parent.resolve()
    target = target.resolve()
    try:
        relative = target.relative_to(parent)
    except ValueError:
        # Links to sibling/parent sections are ordinary content links, not
        # children of this section's sidebar.
        return None

    if not relative.parts:
        return None

    if len(relative.parts) == 1 and target.is_file():
        if target.name.lower() == "index.md":
            return None
        return target.name if target.suffix.lower() == ".md" else None

    first_child = relative.parts[0]
    child_path = parent / first_child
    if child_path.is_dir():
        return first_child
    return None


def build_navigation(index_file: Path, docs_root: Path) -> list[str]:
    """Create ordered direct-child entries from one directory's index.md."""
    entries: list[str] = []
    seen: set[str] = set()

    # Explicitly put the directory index first: Material can attach it to the
    # section title when navigation.indexes is enabled.
    if (index_file.parent / "index.md").is_file():
        entries.append("index.md")
        seen.add("index.md")

    source = index_file.read_text(encoding="utf-8-sig")
    for destination in iter_markdown_destinations(source):
        target = resolve_local_target(destination, index_file, docs_root)
        if target is None:
            continue
        item = nav_item_for_target(target, index_file, docs_root)
        if item and item not in seen:
            entries.append(item)
            seen.add(item)

    entries.append("...")
    return entries


def render_pages(entries: list[str]) -> str:
    lines = [MARKER, "nav:"]
    for entry in entries:
        if entry == "...":
            lines.append("  - ...")
        else:
            # JSON strings are valid YAML scalars and safely handle spaces,
            # apostrophes, accents, colons and other punctuation in paths.
            lines.append(f"  - {json.dumps(entry, ensure_ascii=False)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--docs", default="docs", help="cartella docs di MkDocs (default: docs)")
    parser.add_argument("--check", action="store_true", help="non scrive; termina con errore se i .pages vanno aggiornati")
    parser.add_argument("--dry-run", action="store_true", help="mostra i cambiamenti previsti senza scrivere")
    args = parser.parse_args()

    docs_root = Path(args.docs).resolve()
    if not docs_root.is_dir():
        print(f"ERRORE: cartella documentazione non trovata: {docs_root}", file=sys.stderr)
        return 2

    index_files = sorted(docs_root.rglob("index.md"), key=lambda p: p.as_posix().casefold())
    planned: dict[Path, str] = {}
    manual_pages: list[Path] = []

    for index_file in index_files:
        pages_file = index_file.parent / ".pages"
        existing = pages_file.read_text(encoding="utf-8-sig") if pages_file.exists() else None
        if existing is not None and MARKER not in existing:
            manual_pages.append(pages_file)
            continue
        planned[pages_file] = render_pages(build_navigation(index_file, docs_root))

    # Remove stale generated files only if their directory no longer has an index.
    stale: list[Path] = []
    index_dirs = {p.parent.resolve() for p in index_files}
    for pages_file in docs_root.rglob(".pages"):
        if pages_file.parent.resolve() not in index_dirs:
            content = pages_file.read_text(encoding="utf-8-sig")
            if MARKER in content:
                stale.append(pages_file)

    changed = [p for p, content in planned.items()
               if not p.exists() or p.read_text(encoding="utf-8-sig") != content]
    changed.extend(p for p in stale if p not in changed)

    for pages_file in manual_pages:
        print(f"MANUALE: mantengo invariato {pages_file.relative_to(docs_root)}")

    if args.check:
        if changed:
            for path in changed:
                print(f"DA AGGIORNARE: {path.relative_to(docs_root)}")
            print(f"ERRORE: {len(changed)} file .pages non sincronizzati.", file=sys.stderr)
            return 1
        print(f"OK: navigazione sincronizzata ({len(planned)} directory con index.md).")
        return 0

    if args.dry_run:
        for path in changed:
            action = "RIMUOVI" if path in stale else "SCRIVI"
            print(f"{action}: {path.relative_to(docs_root)}")
        print(f"Anteprima: {len(changed)} modifiche; nessun file cambiato.")
        return 0

    for pages_file, content in planned.items():
        if pages_file.exists() and pages_file.read_text(encoding="utf-8-sig") == content:
            continue
        pages_file.write_text(content, encoding="utf-8", newline="\n")
        print(f"AGGIORNATO: {pages_file.relative_to(docs_root)}")

    for pages_file in stale:
        pages_file.unlink()
        print(f"RIMOSSO (indice non più presente): {pages_file.relative_to(docs_root)}")

    print(
        f"Completato: {len(index_files)} index.md esaminati; "
        f"{len(planned) - len(manual_pages)} configurazioni gestite; "
        f"{len(changed)} cambiamenti. Nessun file Markdown rinominato."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
